"""ILSA-TableQA item schema — one place that defines what a benchmark item is.

The annotation template, the scorer, and the scoring harness all import from here
so they cannot drift apart. An item is one question whose gold answer lives in a
specific statistical exhibit (table) of a public ILSA report.

Format on disk: JSON Lines (one item per line) — diff-friendly and streamable.
A flat CSV template is generated by `benchmark/score_benchmark.py --emit-template`.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field

# --- controlled vocabularies (kept in sync with TAXONOMY.md) -----------------

STUDIES = {"PIRLS", "TIMSS", "ICILS", "ICCS"}

# Exhibit types — the structural genres that make ILSA tables hard. See TAXONOMY.md.
EXHIBIT_TYPES = {
    "achievement_distribution",  # mean scale score + SE + percentiles/graphic
    "benchmark_percentages",     # % reaching Advanced/High/Intermediate/Low
    "trend",                     # change across cycles, with significance arrows
    "group_gap",                 # girls vs boys / group means + difference + sig
    "context_relationship",      # achievement by a context variable (home, attitude)
    "percentages_and_averages",  # % of students in a category + their avg achievement
    "policy_categorical",        # encyclopedia cross-country categorical/policy table
    "other",
}

# Reasoning types — the question-answer coding frame. See TAXONOMY.md.
REASONING_TYPES = {
    "lookup_single",        # read one cell
    "lookup_multi",         # read several cells
    "standard_error_read",  # read the SE for an estimate
    "comparison",           # compare two cells/entities
    "extremum",             # highest/lowest/rank
    "benchmark_percentage", # % at a benchmark
    "group_gap",            # difference between groups + direction
    "trend_direction",      # change across cycles (+ significance)
    "aggregation",          # sum/mean/count across cells (numeric reasoning)
    "significance_read",    # is a difference statistically significant?
    "structure_meta",       # what a header/column means (structure understanding)
}

# Answer kinds — decide which scorer runs (see benchmark/scorer.py:score_item).
ANSWER_KINDS = {
    "numeric_single",  # one number (numeric-exact-with-tolerance)
    "numeric_multi",   # several numbers (set match, F1)
    "direction",       # up / down / flat
    "boolean",         # yes/no, significant/not
    "set",             # set of categorical items (text F1)
    "text",            # free-text / single category (text F1)
}

UNITS = {"percent", "scale_score", "se", "years", "count", "none"}


@dataclass
class TableQAItem:
    id: str
    study: str
    cycle: str                       # e.g. "2021"
    source_document: str             # PDF filename in datasets/ (or report id)
    exhibit_id: str                  # e.g. "Exhibit 6"
    exhibit_type: str                # one of EXHIBIT_TYPES
    question: str
    reasoning_type: str              # one of REASONING_TYPES
    answer_kind: str                 # one of ANSWER_KINDS
    gold_answer: str                 # canonical human-readable answer
    reference_context: str           # serialized table region / caption (gold evidence)
    gold_values: list = field(default_factory=list)   # numeric targets (numeric kinds)
    gold_unit: str = "none"          # one of UNITS
    tolerance: dict | None = None    # {"kind":"abs"|"rel","value":float}; None -> unit default
    gold_cells: list = field(default_factory=list)     # header-paths or "row|col" coords
    source_page: int | None = None
    annotator: str = ""
    notes: str = ""

    def to_dict(self) -> dict:
        return asdict(self)

    @staticmethod
    def from_dict(d: dict) -> "TableQAItem":
        allowed = TableQAItem.__dataclass_fields__.keys()
        return TableQAItem(**{k: d.get(k) for k in allowed if k in d})


REQUIRED = ("id", "study", "cycle", "source_document", "exhibit_id", "exhibit_type",
            "question", "reasoning_type", "answer_kind", "gold_answer", "reference_context")


def validate(item) -> list[str]:
    """Return a list of human-readable problems ([] means valid). Used by the
    harness before scoring and by annotators as a lint step."""
    d = item.to_dict() if isinstance(item, TableQAItem) else dict(item)
    problems: list[str] = []
    for k in REQUIRED:
        if not str(d.get(k, "")).strip():
            problems.append(f"missing required field: {k}")
    if d.get("study") not in STUDIES:
        problems.append(f"study {d.get('study')!r} not in {sorted(STUDIES)}")
    if d.get("exhibit_type") not in EXHIBIT_TYPES:
        problems.append(f"exhibit_type {d.get('exhibit_type')!r} invalid")
    if d.get("reasoning_type") not in REASONING_TYPES:
        problems.append(f"reasoning_type {d.get('reasoning_type')!r} invalid")
    if d.get("answer_kind") not in ANSWER_KINDS:
        problems.append(f"answer_kind {d.get('answer_kind')!r} invalid")
    if d.get("gold_unit", "none") not in UNITS:
        problems.append(f"gold_unit {d.get('gold_unit')!r} invalid")
    if d.get("answer_kind") in ("numeric_single", "numeric_multi"):
        gv = d.get("gold_values") or []
        if not gv:
            problems.append("numeric answer_kind requires non-empty gold_values")
        if not all(isinstance(x, (int, float)) for x in gv):
            problems.append("gold_values must all be numbers")
        if d.get("answer_kind") == "numeric_single" and len(gv) != 1:
            problems.append("numeric_single expects exactly one gold value")
    tol = d.get("tolerance")
    if tol is not None and (tol.get("kind") not in ("abs", "rel") or "value" not in tol):
        problems.append("tolerance must be {'kind':'abs'|'rel','value':float}")
    return problems


def read_jsonl(path) -> list[TableQAItem]:
    items = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("//"):
                items.append(TableQAItem.from_dict(json.loads(line)))
    return items


def write_jsonl(path, items) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        for it in items:
            d = it.to_dict() if isinstance(it, TableQAItem) else it
            fh.write(json.dumps(d, ensure_ascii=False) + "\n")


